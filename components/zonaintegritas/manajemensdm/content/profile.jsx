export const getEmployeesByPage = (page = 1, itemsPerPage = 10) => {
  const startIndex = (page - 1) * itemsPerPage;
  const endIndex = startIndex + itemsPerPage;
  return {
    data: employees.slice(startIndex, endIndex),
    currentPage: page,
    totalPages: Math.ceil(employees.length / itemsPerPage),
    totalItems: employees.length,
    itemsPerPage
  };
};

// ============================
// FUNGSI PERHITUNGAN STATISTIK
// ============================
export const calculateStats = () => {
  const totalPegawai = employees.length;
  const lakiLaki = employees.filter(e => e.gender === "Laki-Laki").length;
  const perempuan = employees.filter(e => e.gender === "Perempuan").length;
  const fungsional = employees.filter(e => e.tipe === "Fungsional").length;
  const pelaksana = employees.filter(e => e.tipe === "Pelaksana").length;
  const struktural = employees.filter(e => 
    e.jabatan.includes("Kepala") || 
    e.jabatan.includes("Kepala Bagian") ||
    e.jabatan.includes("Kepala Bidang")
  ).length;

  return {
    totalPegawai,
    lakiLaki,
    perempuan,
    fungsional,
    pelaksana,
    struktural,
    persenLakiLaki: totalPegawai > 0 ? ((lakiLaki / totalPegawai) * 100).toFixed(1) : "0",
    persenPerempuan: totalPegawai > 0 ? ((perempuan / totalPegawai) * 100).toFixed(1) : "0",
    persenFungsional: totalPegawai > 0 ? ((fungsional / totalPegawai) * 100).toFixed(1) : "0",
    persenPelaksana: totalPegawai > 0 ? ((pelaksana / totalPegawai) * 100).toFixed(1) : "0",
  };
};

